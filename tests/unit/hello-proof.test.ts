import { describe, expect, it } from "vitest";
import * as Proto from "../../shared/remote-protocol.mjs";

// eslint-disable-next-line @typescript-eslint/no-explicit-any
const P = Proto as any;

describe("hello proof", () => {
  it("verifies a valid hello exchange", async () => {
    const hostIdentity = await P.generateIdentity(true);
    const hostId = await P.idOf(hostIdentity.publicRaw);

    const req = await P.helloRequest();
    expect(req.body.v).toBe(P.PROTOCOL_VERSION);
    expect(typeof req.body.ePub).toBe("string");
    expect(typeof req.body.nonce).toBe("string");

    const res = await P.helloResponse(hostIdentity, hostId, req.body);
    expect(res).not.toBeNull();
    expect(res.app).toBe("uniview");
    expect(res.hostId).toBe(hostId);
    expect(typeof res.proof).toBe("string");

    const ok = await req.verify(hostIdentity.publicRaw, hostId, res);
    expect(ok).toBe(true);
  });

  it("fails when hostId does not match", async () => {
    const hostIdentity = await P.generateIdentity(true);
    const hostId = await P.idOf(hostIdentity.publicRaw);

    const req = await P.helloRequest();
    const res = await P.helloResponse(hostIdentity, hostId, req.body);
    expect(res).not.toBeNull();

    const ok = await req.verify(hostIdentity.publicRaw, "wrong-host-id", res);
    expect(ok).toBe(false);
  });

  it("fails with wrong proof", async () => {
    const hostIdentity = await P.generateIdentity(true);
    const hostId = await P.idOf(hostIdentity.publicRaw);

    const req = await P.helloRequest();
    const res = await P.helloResponse(hostIdentity, hostId, req.body);
    expect(res).not.toBeNull();

    const tampered = { ...res, proof: P.b64u(new Uint8Array(32).fill(1)) };
    const ok = await req.verify(hostIdentity.publicRaw, hostId, tampered);
    expect(ok).toBe(false);
  });

  it("fails when verified with another host's public key", async () => {
    const host1 = await P.generateIdentity(true);
    const host2 = await P.generateIdentity(true);
    const host1Id = await P.idOf(host1.publicRaw);

    const req = await P.helloRequest();
    const res = await P.helloResponse(host1, host1Id, req.body);
    expect(res).not.toBeNull();

    const ok = await req.verify(host2.publicRaw, host1Id, res);
    expect(ok).toBe(false);
  });

  it("fails when response was generated by another host's key", async () => {
    const host1 = await P.generateIdentity(true);
    const host2 = await P.generateIdentity(true);
    const host1Id = await P.idOf(host1.publicRaw);

    const req = await P.helloRequest();
    const res = await P.helloResponse(host2, host1Id, req.body);
    expect(res).not.toBeNull();

    const ok = await req.verify(host1.publicRaw, host1Id, res);
    expect(ok).toBe(false);
  });

  it("returns null for malformed bodies in helloResponse", async () => {
    const hostIdentity = await P.generateIdentity(true);
    const hostId = await P.idOf(hostIdentity.publicRaw);

    expect(await P.helloResponse(hostIdentity, hostId, null)).toBeNull();
    expect(await P.helloResponse(hostIdentity, hostId, "bad")).toBeNull();

    const bad1 = { ePub: P.b64u(new Uint8Array(65)) };
    expect(await P.helloResponse(hostIdentity, hostId, bad1)).toBeNull();

    const badNonce = { ePub: P.b64u(new Uint8Array(65)), nonce: P.b64u(new Uint8Array(10)) };
    expect(await P.helloResponse(hostIdentity, hostId, badNonce)).toBeNull();

    const badPubLen = { ePub: P.b64u(new Uint8Array(32)), nonce: P.b64u(new Uint8Array(16)) };
    expect(await P.helloResponse(hostIdentity, hostId, badPubLen)).toBeNull();

    const missingPub = { nonce: P.b64u(new Uint8Array(16)) };
    expect(await P.helloResponse(hostIdentity, hostId, missingPub)).toBeNull();

    const badEncoding = { ePub: "not-valid-base64!!!", nonce: P.b64u(new Uint8Array(16)) };
    expect(await P.helloResponse(hostIdentity, hostId, badEncoding)).toBeNull();
  });

  it("returns false in verify for malformed response or json", async () => {
    const hostIdentity = await P.generateIdentity(true);
    const hostId = await P.idOf(hostIdentity.publicRaw);

    const req = await P.helloRequest();
    expect(await req.verify(hostIdentity.publicRaw, hostId, null)).toBe(false);
    expect(await req.verify(hostIdentity.publicRaw, hostId, "bad")).toBe(false);
    expect(await req.verify(hostIdentity.publicRaw, hostId, { app: "other", hostId })).toBe(false);
    expect(await req.verify(hostIdentity.publicRaw, hostId, { app: "uniview", hostId, proof: "bad!base64" })).toBe(false);
    expect(await req.verify(hostIdentity.publicRaw, hostId, { app: "uniview", hostId, proof: P.b64u(new Uint8Array(16)) })).toBe(false);
  });
});
